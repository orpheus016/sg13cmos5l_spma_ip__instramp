"""Markdown for the numbers that belong under the pictures (stdlib only; used by update_images.py and make_readme.py).

docs/<cell>/media/<cell>_info.json (written by scripts/update_images.py) holds
  params: [{source, instances, name, value}]   the `.param` lines of the schematic (and of the sub-cells it instantiates)
  layout: {top, W, L, area}                    bounding box of the top cell in um / um^2
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(cell):
    f = os.path.join(ROOT, "docs", cell, "media", f"{cell}_info.json")
    return json.load(open(f)) if os.path.isfile(f) else {}


def params_md(info, sch_path=None):
    """table of the schematic parameters, '' when there are none"""
    rows = info.get("params") or []
    if not rows:
        return ""
    multi = any(r["source"] != info.get("cell") or r.get("instances") for r in rows)   # inherited from a sub-cell: name the source
    head = "| Source | Parameter | Value |\n|---|---|---|" if multi else "| Parameter | Value |\n|---|---|"
    out = []
    for r in rows:
        src = r["source"] + (f" ({', '.join(r['instances'])})" if r.get("instances") else "")
        cells = [f"`{r['name']}`", f"`{r['value']}`"]
        out.append("| " + " | ".join(([src] if multi else []) + cells) + " |")
    note = f"**Parameters** (`.param` of the schematic{' and of the cells it instantiates' if multi else ''}; generated by `scripts/update_images.py`, do not edit)"
    return note + "\n\n" + head + "\n" + "\n".join(out)


def layout_md(info):
    """table of the physical size, '' when unknown"""
    lay = info.get("layout")
    if not lay:
        return ""
    return ("**Physical size** (bounding box of `" + lay["top"] + "`; generated by `scripts/update_images.py`)\n\n"
            "| Width W | Length L | Area |\n|---|---|---|\n"
            f"| {lay['W']:.2f} µm | {lay['L']:.2f} µm | {lay['area']:.0f} µm² |")
